#!/usr/bin/env python3
"""
Draft the department's system-generated semester report from the live API.

Every number is read from `GET /api/reports/semester` (plus the per-faculty and per-course
reports), so the document always matches what the coordinator sees on screen. Run the backend,
then:

    python3 scripts/generate_system_report.py

Output: docs/samples/system-generated-report.md
"""
import http.cookiejar
import json
import urllib.request
from pathlib import Path

BASE = "http://localhost:8080"
ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "samples" / "system-generated-report.md"


def client(email):
    jar = http.cookiejar.CookieJar()
    opener = urllib.request.build_opener(urllib.request.HTTPCookieProcessor(jar))

    def get(path):
        with opener.open(urllib.request.Request(BASE + path)) as res:
            return json.loads(res.read().decode())

    body = json.dumps({"email": email}).encode()
    with opener.open(urllib.request.Request(
            BASE + "/api/auth/dev-login", data=body,
            headers={"Content-Type": "application/json"})) as res:
        res.read()
    return get


def table(headers, rows):
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join(["---"] * len(headers)) + "|"]
    for row in rows:
        out.append("| " + " | ".join(str(c) for c in row) + " |")
    return "\n".join(out)


def main():
    get = client("coordinator@iet.edu")
    r = get("/api/reports/semester")
    meta = r["meta"]

    lines = []
    lines.append("# System-Generated Semester & Faculty Performance Report")
    lines.append("")
    lines.append(f"*Generated by the Faculty Dashboard from live teaching logs · Term: {meta['termName']} "
                 f"· Week {meta['currentWeek']} of {meta['totalWeeks']} · {meta['generatedAt']}*")
    lines.append("")
    lines.append("Every figure below is computed from the database: allocations, timetable, session logs, "
                 "syllabi, assessments, remedial plans and deadline submissions. Nothing is typed by hand.")
    lines.append("")

    # 1. Scorecard
    lines.append("## 1. Executive scorecard")
    lines.append("")
    lines.append(table(["Metric", "Target", "Actual", "Status", "Note"],
                       [[s["metric"], s["target"], s["actual"], s["status"], s["note"]] for s in r["scorecard"]]))
    lines.append("")

    # 2. Critical cases
    critical = [c for c in r["criticalCases"] if c["severity"] == "CRITICAL"]
    warnings = [c for c in r["criticalCases"] if c["severity"] == "WARNING"]
    lines.append("## 2. Critical cases (immediate action)")
    lines.append("")
    lines.append(f"{len(critical)} critical, {len(warnings)} warnings. The first 15 critical cases:")
    lines.append("")
    top = (critical + warnings)[:15]
    lines.append(table(["Ref", "Severity", "Category", "Entity", "Faculty", "Students", "Detail", "Action"],
                       [[c["ref"], c["severity"], c["category"], c["entity"], c["facultyName"],
                         c["studentsAffected"], c["description"], c["requiredAction"]] for c in top]))
    lines.append("")

    # 3. Irregular / mismatch audit
    lines.append("## 3. Irregular courses & allocation mismatch audit")
    lines.append("")
    if r["mismatches"]:
        lines.append(table(["Course", "Yr/Sem", "Sec", "L-T-P", "Component", "Planned", "Allocated", "Type", "Detail"],
                           [[m["courseCode"], f"{m['yearOfStudy']}/{m['semester']}", m["section"], m["ltp"],
                             m["component"], m["plannedHours"], m["assignedHours"], m["type"], m["detail"]]
                            for m in r["mismatches"][:25]]))
    else:
        lines.append("Every section's allocation matches its L-T-P plan.")
    lines.append("")

    # 4. Course-wise performance by year
    lines.append("## 4. Course-wise performance by year")
    lines.append("")
    for year in sorted({s["yearOfStudy"] for s in r["sections"]}):
        rows = [s for s in r["sections"] if s["yearOfStudy"] == year]
        students = sum(s["students"] or 0 for s in rows)
        lines.append(f"### Year {year} — {students} students across {len(rows)} sections")
        lines.append("")
        lines.append(table(["Course", "Sec", "Students", "Components", "Faculty", "Coverage", "Pacing",
                            "Held/Due", "CIE", "Remedial"],
                           [[s["courseCode"], s["section"], s["students"], s["components"], s["faculty"],
                             f"{s['coveredTopics']}/{s['totalTopics']} ({s['coveragePct']}%)", s["pacingStatus"],
                             f"{s['held']}/{s['scheduled']}", s["assessmentsHeld"], s["remedialStatus"]]
                            for s in rows]))
        lines.append("")

    # 5. Faculty-wise multi-course breakdown
    lines.append("## 5. Faculty-wise performance (multi-course, year-wise)")
    lines.append("")
    for f in r["faculty"]:
        codes = sorted({l["courseCode"] for l in f["lines"]})
        lines.append(f"### {f['name']} — {', '.join(codes) if codes else 'no allocations'}")
        lines.append("")
        lines.append(f"Load {f['totalHours']}h/week (L{f['lectureHours']} T{f['tutorialHours']} "
                     f"P{f['practicalHours']} PBL{f['pblHours']}) · students taught {f['studentsTaught']} "
                     f"· years {f['years']} · logged {f['held']}/{f['scheduled']}"
                     + (f" · logging rate {f['loggingRate']}%" if f["loggingRate"] is not None else ""))
        lines.append("")
        lines.append(table(["Year", "Course", "Section", "Component", "Weekly h", "Students", "Held/Due",
                            "Coverage", "Pacing", "CIE", "Remedial"],
                           [[l["yearOfStudy"], l["courseCode"], l["section"], l["component"], l["weeklyHours"],
                             l["students"], f"{l['held']}/{l['scheduled']}", f"{l['coveragePct']}%",
                             l["pacingStatus"], l["assessmentsHeld"], l["remedialStatus"]] for l in f["lines"]]))
        lines.append("")

    # 6. Continuous assessment and remedial plans
    lines.append("## 6. Continuous assessment (CIE) and remedial plans")
    lines.append("")
    lines.append(f"Each section is to hold {meta['requiredAssessments']} continuous assessments this semester.")
    lines.append("")
    lines.append(table(["Checkpoint", "Sections done", "Sections total", "Class average"],
                       [[f"CIE-{a['index']}", a["sectionsDone"], a["sectionsTotal"],
                         f"{a['averagePct']}%" if a["averagePct"] is not None else "—"] for a in r["assessments"]]))
    lines.append("")
    lines.append("### Remedial plans filed")
    lines.append("")
    if r["remedialPlans"]:
        lines.append(table(["Course", "Sec", "Faculty", "Reason", "Action", "Extra", "Target", "Status"],
                           [[p["courseCode"], p["section"], p["facultyName"], p["reason"], p["action"],
                             p["extraSessions"], p["targetDate"], p["status"]] for p in r["remedialPlans"]]))
    else:
        lines.append("No remedial plans filed.")
    lines.append("")

    # 7. Data sources
    d = r["dataSources"]
    lines.append("## 7. Data sources")
    lines.append("")
    lines.append(table(["Source", "Count"], [
        ["Faculty with allocations", d["faculty"]],
        ["Allocations (load sheet)", d["allocations"]],
        ["Course sections", d["sections"]],
        ["Timetable slots", d["timetableSlots"]],
        ["Classes logged", d["sessionsLogged"]],
        ["Syllabus topics", d["syllabusTopics"]],
        ["Assessments recorded", d["assessments"]],
        ["Remedial plans", d["remedialPlans"]],
    ]))
    lines.append("")

    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT.relative_to(ROOT)} ({len(lines)} lines)")


if __name__ == "__main__":
    main()
